//! The built-in tables: a small subset of CLDR (the Unicode Common Locale
//! Data Repository) for the languages Stipple formats without asking the OS:
//! separators, number, percent and currency patterns, date and time
//! patterns, month and weekday names, and the AM/PM markers.
//!
//! Patterns use CLDR's syntax (`d MMM y`, `h:mm a`); `#` in a number pattern
//! is the number and `¤` the currency symbol. Weekday arrays start on Monday.

/// What one language writes, in its most likely region.
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct LangData {
    pub lang: &'static str,
    /// The region assumed when a tag names none (CLDR's likely subtags).
    pub region: &'static str,
    pub decimal: &'static str,
    pub group: &'static str,
    /// The fewest digits before the first group: 2 leaves "1234" ungrouped.
    pub min_group: u8,
    pub minus: &'static str,
    pub percent: &'static str,
    pub currency: &'static str,
    /// Short, medium, long and full date patterns.
    pub dates: [&'static str; 4],
    /// Short and medium time patterns on a 12-hour clock.
    pub time12: [&'static str; 2],
    /// Short and medium time patterns on a 24-hour clock.
    pub time23: [&'static str; 2],
    /// How a date (`{1}`) and a time (`{0}`) are joined: short and medium
    /// dates, then long and full ones.
    pub glue: [&'static str; 2],
    pub months: [&'static str; 12],
    pub months_abbr: [&'static str; 12],
    pub days: [&'static str; 7],
    pub days_abbr: [&'static str; 7],
    pub am_pm: [&'static str; 2],
}

