/// The table for `lang` (a lowercase primary language subtag), if there is
/// one. Norwegian Bokmål's old code and Hebrew's are folded in.
pub(crate) fn lang(lang: &str) -> Option<&'static LangData> {
    let lang = match lang {
        "iw" => "he",
        other => other,
    };
    LANGS.iter().find(|d| d.lang == lang)
}

